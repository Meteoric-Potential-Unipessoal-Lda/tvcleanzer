#!/usr/bin/env python3
"""Generates launcher/src/com/tvcleanzer/launcher/T.java — the TV launcher's translations.

Keys are the Russian literals passed to T.t("…") / T.f("…", …) in launcher/src (a literal may be
split with + across lines). For every language in langs.json a key is looked up in
  1. tools/l10n/launcher/<lang>.json  ({"русский": "translation"}, launcher-only strings), then
  2. the app tables (keys.json + tr_<lang>.json), so shared strings are translated once.
Missing ones fall back to Russian on the TV and are listed here; {0}/{1} must match.

Run from the repo root:  python3 tools/l10n/gen_launcher.py
"""
import json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
L10N = os.path.join(ROOT, 'tools', 'l10n')
SRC = os.path.join(ROOT, 'launcher', 'src', 'com', 'tvcleanzer', 'launcher')
OUT = os.path.join(SRC, 'T.java')

ESC = {'n': '\n', 't': '\t', '"': '"', "'": "'", '\\': '\\', 'r': '\r'}


def literal(s, i):
    """Parses a Java string literal starting at s[i] == '"'; returns (value, index after it)."""
    i += 1
    out = []
    while s[i] != '"':
        c = s[i]
        if c == '\\':
            n = s[i + 1]
            if n == 'u':
                out.append(chr(int(s[i + 2:i + 6], 16)))
                i += 6
                continue
            out.append(ESC[n])
            i += 2
            continue
        out.append(c)
        i += 1
    return ''.join(out), i + 1


def keys_from_sources():
    keys = []
    for name in sorted(os.listdir(SRC)):
        if not name.endswith('.java') or name == 'T.java':
            continue
        s = open(os.path.join(SRC, name), encoding='utf-8').read()
        for m in re.finditer(r'\bT\.[tf]\(\s*', s):
            i = m.end()
            if s[i] != '"':
                continue  # T.t(variable): nothing to collect
            parts = []
            while True:
                v, i = literal(s, i)
                parts.append(v)
                j = i
                while s[j].isspace():
                    j += 1
                if s[j] != '+':
                    break
                j += 1
                while s[j].isspace():
                    j += 1
                if s[j] != '"':
                    break
                i = j
            k = ''.join(parts)
            if k not in keys:
                keys.append(k)
    return keys


def java(s):
    s = s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t')
    return '"' + s + '"'


PH = re.compile(r'\{\d\}')


def main():
    keys = keys_from_sources()
    langs = json.load(open(os.path.join(L10N, 'langs.json')))
    app_keys = json.load(open(os.path.join(L10N, 'keys.json')))
    app_idx = {k: i for i, k in enumerate(app_keys)}
    tables, bad = {}, 0
    for l in langs:
        own_path = os.path.join(L10N, 'launcher', l + '.json')
        own = json.load(open(own_path)) if os.path.exists(own_path) else {}
        app = json.load(open(os.path.join(L10N, 'tr_%s.json' % l)))
        row, missing = [], []
        for k in keys:
            v = own.get(k) or (app[app_idx[k]] if k in app_idx else '')
            if v and sorted(PH.findall(v)) != sorted(PH.findall(k)):
                print('%s: placeholders differ: %r → %r' % (l, k, v))
                bad += 1
                v = ''
            if not v:
                missing.append(k)
            row.append(v or None)
        if missing:
            print('%s: %d untranslated (shown in Russian): %s' % (l, len(missing), ' | '.join(missing[:5])))
        tables[l] = row

    cls = {l: l.capitalize() for l in langs}
    w = []
    w.append('// GENERATED by tools/l10n/gen_launcher.py — do not edit; change the JSON tables instead.')
    w.append('package com.tvcleanzer.launcher;')
    w.append('')
    w.append('import java.util.HashMap;')
    w.append('import java.util.Locale;')
    w.append('')
    w.append('/** UI strings: Russian source text in, the TV language out (Russian when untranslated). */')
    w.append('final class T {')
    w.append('    private T() {}')
    w.append('')
    w.append('    private static String cur;')
    w.append('    private static HashMap<String, String> map;')
    w.append('')
    w.append('    static synchronized String t(String ru) {')
    w.append('        String l = lang();')
    w.append('        if (!l.equals(cur)) {')
    w.append('            cur = l;')
    w.append('            map = build(table(l));')
    w.append('        }')
    w.append('        String v = map == null ? null : map.get(ru);')
    w.append('        return v == null ? ru : v;')
    w.append('    }')
    w.append('')
    w.append('    /** t() plus {0}, {1}… replaced by the arguments. */')
    w.append('    static String f(String ru, Object... args) {')
    w.append('        String s = t(ru);')
    w.append('        for (int i = 0; i < args.length; i++) s = s.replace("{" + i + "}", String.valueOf(args[i]));')
    w.append('        return s;')
    w.append('    }')
    w.append('')
    w.append('    /** Language code of the TV; Russian for ru and for languages we fall back to Russian. */')
    w.append('    static String lang() {')
    w.append('        String l = Locale.getDefault().getLanguage();')
    w.append('        if (l == null || l.isEmpty()) return "en";')
    w.append('        switch (l) {')
    w.append('            case "ru": case "tg": case "tk": case "mo": return "ru";')
    w.append('            case "in": return "id";')
    w.append('            case "nb": case "nn": case "no": return "en";')
    w.append('        }')
    w.append('        switch (l) {')
    w.append('            ' + ' '.join('case "%s":' % l for l in langs) + ' return l;')
    w.append('        }')
    w.append('        return "en";')
    w.append('    }')
    w.append('')
    w.append('    private static HashMap<String, String> build(String[] tr) {')
    w.append('        if (tr == null) return null;')
    w.append('        HashMap<String, String> m = new HashMap<>(tr.length * 2);')
    w.append('        for (int i = 0; i < tr.length; i++) if (tr[i] != null) m.put(RU[i], tr[i]);')
    w.append('        return m;')
    w.append('    }')
    w.append('')
    w.append('    private static String[] table(String l) {')
    w.append('        switch (l) {')
    for l in langs:
        w.append('            case "%s": return %s.A;' % (l, cls[l]))
    w.append('            default: return null;')
    w.append('        }')
    w.append('    }')
    w.append('')
    w.append('    private static final String[] RU = {')
    for k in keys:
        w.append('        ' + java(k) + ',')
    w.append('    };')
    for l in langs:
        w.append('')
        w.append('    /** %s; a nested class so only the TV language is loaded. */' % l)
        w.append('    private static final class %s {' % cls[l])
        w.append('        static final String[] A = {')
        for v in tables[l]:
            w.append('            ' + ('null' if v is None else java(v)) + ',')
        w.append('        };')
        w.append('    }')
    w.append('}')
    w.append('')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(w))
    print('T.java: %d strings × %d languages' % (len(keys), len(langs)))
    if bad:
        sys.exit(1)


if __name__ == '__main__':
    main()
