"""Builds lib/l10n/strings.dart from keys.json (Russian sources) and tr_<lang>.json
(translations in the same order; empty string = not translated, falls back to English).
Checks that {0}/{1}… placeholders and line breaks survive translation.
Usage: python3 tools/l10n/gen.py   (from the repo root)"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
LANGS = json.load(open(f'{HERE}/langs.json'))  # without 'ru' (the source)
keys = json.load(open(f'{HERE}/keys.json'))

def esc(x):
    return x.replace('\\', '\\\\').replace('\n', '\\n').replace("'", "\\'").replace('$', '\\$')

ph = re.compile(r'\{\d+\}')
bad = 0
out = ['// Generated by tools/l10n/gen.py from tools/l10n/*.json — do not edit by hand.',
       '', 'const Map<String, Map<String, String>> translations = {']
for l in LANGS:
    tab = json.load(open(f'{HERE}/tr_{l}.json'))
    if len(tab) != len(keys):
        sys.exit(f'tr_{l}.json: {len(tab)} rows, keys.json: {len(keys)}')
    out.append(f"  '{l}': {{")
    for k, v in zip(keys, tab):
        if not v:
            continue
        if sorted(ph.findall(k)) != sorted(ph.findall(v)):
            print(f'{l}: placeholders differ: {k[:60]!r} -> {v[:60]!r}')
            bad += 1
            continue
        out.append(f"    '{esc(k)}': '{esc(v)}',")
    out.append('  },')
out.append('};')
open(f'{ROOT}/lib/l10n/strings.dart', 'w').write('\n'.join(out) + '\n')
print(f'{len(LANGS)} languages, {len(keys)} strings, {bad} rows skipped')
sys.exit(1 if bad else 0)
